import numpy as np
import matplotlib.pyplot as plt
from PIL import Image
from sklearn.ensemble import RandomForestClassifier
import os

# 1. Load the Oredo image we used earlier
img_path = "/content/drive/MyDrive/Edosat_v0.1_NDVI/Oredo.png"
img = Image.open(img_path)
img_array = np.array(img)

# 2. Define our "Training Data" (Ground Truth)
# We will pick specific pixels (Y, X) that we know are Forest or Urban
# (You can change these coordinates later if you want)
forest_points = [(100, 100), (150, 200), (200, 150), (50, 300)]
urban_points = [(800, 800), (900, 850), (750, 900), (1000, 1000)]

# 3. Extract the features (colors) for these points
X_train = []
y_train = [] # 0 for Urban, 1 for Forest

for pt in forest_points:
    X_train.append(img_array[pt[0], pt[1]])
    y_train.append(1) # Label as Forest

for pt in urban_points:
    X_train.append(img_array[pt[0], pt[1]])
    y_train.append(0) # Label as Urban

X_train = np.array(X_train)
y_train = np.array(y_train)

print("Training Supervised AI Model (Random Forest)...")
# 4. Train the AI
clf = RandomForestClassifier(n_estimators=100, random_state=42)
clf.fit(X_train, y_train)

# 5. Now, predict the whole image!
print("Predicting all pixels in Edo State...")
# Reshape the image so the AI can read every pixel
pixels = img_array.reshape(-1, 3)
predictions = clf.predict(pixels)

# 6. Create a new image based on the AI's predictions
# If AI says Forest (1), make it Green. If Urban (0), make it Grey.
new_img = np.zeros_like(pixels)
new_img[predictions == 1] = [0, 255, 0]   # Green for Forest
new_img[predictions == 0] = [128, 128, 128] # Grey for Urban

# Reshape back to image format
supervised_img = new_img.reshape(img_array.shape).astype('uint8')

# 7. Show the result!
fig, ax = plt.subplots(1, 2, figsize=(15, 7))
ax[0].imshow(img)
ax[0].set_title("Original Edosat Image (Oredo)")
ax[0].axis('off')

ax[1].imshow(supervised_img)
ax[1].set_title("Supervised AI: Forest (Green) vs Urban (Grey)")
ax[1].axis('off')
plt.show()

print("✅ Supervised AI Model trained and applied!")